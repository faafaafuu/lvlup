import { CATALOG, UnitId } from '@levelup/domain';

export const UNIT_IDS = [
  'g', 'ml', 'piece', 'plate', 'bowl', 'serving', 'slice', 'glass', 'cup',
  'tbsp', 'tsp', 'handful', 'pack', 'bottle', 'can', 'bar', 'square',
] as const satisfies readonly UnitId[];

/**
 * Системный промпт стабилен байт-в-байт (каталог в фиксированном порядке) —
 * так его можно кэшировать. Пользовательская фраза идёт только в messages.
 */
export const SYSTEM_PROMPT = `Ты разбираешь фразу пользователя о том, что он съел или выпил, на отдельные позиции.
Фраза пришла из распознавания речи на русском: возможны ошибки, разговорные формы, лишние слова.

Для каждой позиции верни:
- text: название блюда в именительном падеже, как сказал пользователь («бутерброд с колбасой»).
- foodId: id из каталога ниже, если позиция ему соответствует; иначе null. Выбирай самое конкретное совпадение («чай с сахаром» → tea_sugar, а не tea).
- quantity: число, если количество названо («два» → 2, «полтарелки» → 0.5, «пара» → 2); иначе null. Не придумывай.
- unit: единица, если названа: ${UNIT_IDS.join(', ')}. Тарелка — plate, кружка/чашка — cup, кусок/ломтик/кусочек — slice, штука — piece, столовая ложка — tbsp, чайная — tsp. Иначе null.
- grams: только если явно назван вес или объём («200 грамм» → 200, «пол литра» → 500, «кило» → 1000); иначе null.

Правила:
- Одна позиция — одно блюдо. «Гречка с котлетой» — две позиции, если в каталоге нет такого готового блюда.
- Добавки к напитку («кофе с молоком», «чай с сахаром») ищи как готовую позицию каталога.
- Игнорируй всё, что не еда и не напиток. Если еды нет — верни пустой список.

Каталог (id: название):
${CATALOG.map((f) => `${f.id}: ${f.name}`).join('\n')}`;
