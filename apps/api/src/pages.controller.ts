import { Controller, Get, Header, Inject } from '@nestjs/common';
import { AppConfig } from './config';
import { APP_CONFIG } from './tokens';

/** Страницы для App Store: политика конфиденциальности и поддержка (ссылки в карточке приложения). */
@Controller()
export class PagesController {
  constructor(@Inject(APP_CONFIG) private readonly config: AppConfig) {}

  @Get('privacy')
  @Header('content-type', 'text/html; charset=utf-8')
  privacy(): string {
    return page('Политика конфиденциальности', PRIVACY(this.contact()));
  }

  @Get('support')
  @Header('content-type', 'text/html; charset=utf-8')
  support(): string {
    return page('Поддержка', SUPPORT(this.contact()));
  }

  @Get()
  @Header('content-type', 'text/html; charset=utf-8')
  index(): string {
    return page('Хрум', `<p>Хрум — дневник еды голосом: скажи, что съел, и калории посчитаются сами.</p>
<p><a href="/privacy">Политика конфиденциальности</a> · <a href="/support">Поддержка</a></p>`);
  }

  private contact(): string {
    const email = this.config.supportEmail;
    return email ? `<a href="mailto:${email}">${email}</a>` : 'через страницу приложения в App Store';
  }
}

const PRIVACY = (contact: string) => `
<p>Обновлено: 5 ноября 2026 года.</p>
<p>Хрум — дневник питания и активности. Мы собираем минимум данных и не продаём их.</p>
<h2>Что хранится на телефоне</h2>
<p>Все записи о еде, весе, шагах и тренировках, профиль и настройки хранятся только на вашем устройстве. Аккаунтов нет. Удалить всё можно в «Настройки → Сбросить данные» или удалив приложение.</p>
<h2>Apple Здоровье</h2>
<p>С вашего разрешения Хрум читает из Apple Здоровье шаги, сон, вес, активные калории и тренировки, чтобы показывать их в дневнике. Эти данные обрабатываются только на устройстве, никуда не передаются, не используются для рекламы и не сохраняются в iCloud.</p>
<h2>Голос и распознавание фраз</h2>
<p>Речь превращается в текст системным распознаванием Apple; звук на наш сервер не отправляется.</p>
<p>Если вы разрешили распознавание с ИИ, текст фразы о еде (например, «тарелка борща и чай») отправляется на наш сервер, а с него — языковой модели (DeepSeek через сервис OpenRouter), чтобы понять блюда и порции. Вместе с фразой передаются ваши настройки порций и вес — для подсчёта калорий тренировок. Имени, контактов и данных из Apple Здоровье в запросе нет.</p>
<p>Без этого разрешения фразы разбираются прямо на телефоне, хуже, но без передачи куда-либо. Разрешение меняется в «Настройки → Распознавание с ИИ».</p>
<h2>Что хранится на сервере</h2>
<p>Для исправления ошибок распознавания сервер записывает текст фразы и результат разбора в журнал, который удаляется через 14 дней. Для дневного лимита запросов используется случайный идентификатор установки приложения — он не связан с вашей личностью. IP-адреса в журнал не записываются.</p>
<h2>Реклама и аналитика</h2>
<p>В Хруме нет рекламы, трекинга и сторонней аналитики.</p>
<h2>Дети</h2>
<p>Хрум не предназначен для детей младше 13 лет и сознательно не собирает их данные.</p>
<h2>Связь</h2>
<p>Вопросы о данных: ${contact}.</p>`;

const SUPPORT = (contact: string) => `
<p>Пишите: ${contact}. Отвечаем в течение пары дней.</p>
<h2>Частые вопросы</h2>
<p><b>Как записать еду?</b> Нажмите на микрофон и скажите, например: «на обед тарелка борща, два куска хлеба и чай».</p>
<p><b>Порция посчиталась неверно.</b> На экране проверки у каждого блюда есть − и +. Уже записанное — нажмите на запись в дневнике.</p>
<p><b>Шаги не подтягиваются.</b> Включите «Apple Здоровье» в настройках Хрума и разрешите доступ в приложении «Здоровье».</p>
<p><b>Как удалить данные?</b> «Настройки → Сбросить данные» или удалите приложение — на сервере ваших записей нет.</p>`;

function page(title: string, body: string): string {
  return `<!doctype html><html lang="ru"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>${title} — Хрум</title>
<style>:root{color-scheme:light dark}body{font:16px/1.55 -apple-system,system-ui,sans-serif;max-width:680px;margin:0 auto;padding:32px 16px;background:#fff;color:#111}
h1{font-weight:300;font-size:32px}h2{font-size:18px;margin-top:28px}a{color:#1E86F0}
@media (prefers-color-scheme:dark){body{background:#0A0A0C;color:#eee}}</style></head>
<body><h1>${title}</h1>${body}</body></html>`;
}
